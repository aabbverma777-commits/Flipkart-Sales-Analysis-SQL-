/*
Q51. Which sales orders have an order value greater than the
    average order value of all sales?

*/

SELECT
    Order_ID,
    Customer_ID,
    Total_Amount
FROM sales
WHERE Total_Amount > (
    SELECT AVG(Total_Amount)
    FROM sales
)
ORDER BY Total_Amount DESC;


/*
Q52. Which products have an average rating higher than the
    overall average product rating?

*/

SELECT
    Product_ID,
    Product_Name,
    Avg_Rating
FROM products
WHERE Avg_Rating > (
    SELECT AVG(Avg_Rating)
    FROM products
)
ORDER BY Avg_Rating DESC;


