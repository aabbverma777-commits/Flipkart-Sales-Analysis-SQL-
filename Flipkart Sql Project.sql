/* Q30. What is the average rating for each product category? */

SELECT
    Category,
    ROUND(AVG(Avg_Rating), 2) AS Average_Rating
FROM products
GROUP BY Category
ORDER BY Average_Rating DESC;


/* Q31. Which categories contain the largest number of products? */

SELECT
    Category,
    COUNT(*) AS Product_Count
FROM products
GROUP BY Category
