/* Q34. What is the revenue generated by each product category? */

SELECT
    p.Category,
    ROUND(SUM(s.Total_Amount), 2) AS Total_Revenue
FROM sales s
INNER JOIN products p
    ON s.Product_ID = p.Product_ID
GROUP BY p.Category
ORDER BY Total_Revenue DESC;


/* Q35. What is the revenue generated by each brand? */

SELECT
    p.Brand,
    ROUND(SUM(s.Total_Amount), 2) AS Total_Revenue
FROM sales s
INNER JOIN products p
    ON s.Product_ID = p.Product_ID
GROUP BY p.Brand
ORDER BY Total_Revenue DESC;


/* Q36. Which products generated the highest revenue? */

SELECT
    p.Product_ID,
    p.Product_Name,
    p.Category,
    ROUND(SUM(s.Total_Amount), 2) AS Total_Revenue
FROM sales s
INNER JOIN products p
    ON s.Product_ID = p.Product_ID
GROUP BY
    p.Product_ID,
    p.Product_Name,
    p.Category
ORDER BY Total_Revenue DESC
LIMIT 10;


/* Q37. Which products have the highest sales quantity? */

SELECT
    p.Product_ID,
    p.Product_Name,
    SUM(s.Quantity) AS Total_Quantity_Sold
FROM sales s
INNER JOIN products p
    ON s.Product_ID = p.Product_ID
GROUP BY
    p.Product_ID,
    p.Product_Name
ORDER BY Total_Quantity_Sold DESC
LIMIT 10;


/* Q38. Which category sells the highest quantity? */

SELECT
    p.Category,
    SUM(s.Quantity) AS Total_Quantity_Sold
FROM sales s
INNER JOIN products p
    ON s.Product_ID = p.Product_ID
GROUP BY p.Category
ORDER BY Total_Quantity_Sold DESC
LIMIT 1;


/* ============================================================
   SECTION 5: DISCOUNT & PRICING ANALYSIS
   ============================================================ */


/* Q39. Which products have a discount of 20% or more? */

SELECT
    Product_ID,
    Product_Name,
    Discount_Percent,
    Original_Price,
    Selling_Price
FROM products
WHERE Discount_Percent >= 20
ORDER BY Discount_Percent DESC;


/* Q40. What is the average discount percentage by category? */

SELECT
    Category,
    ROUND(AVG(Discount_Percent), 2) AS Average_Discount_Percent
FROM products
GROUP BY Category
ORDER BY Average_Discount_Percent DESC;


/* Q41. What is the difference between original price
        and selling price? */

SELECT
    Product_ID,
    Product_Name,
    Original_Price,
    Selling_Price,
    ROUND(Original_Price - Selling_Price, 2) AS Price_Difference
FROM products
ORDER BY Price_Difference DESC;


/* Q42. Which products have the highest number of reviews? */

SELECT
    Product_ID,
    Product_Name,
    Total_Reviews,
    Avg_Rating
FROM products
ORDER BY Total_Reviews DESC
LIMIT 10;


/* Q43. How many products are there in each discount bucket? */

SELECT
    CASE
        WHEN Discount_Percent = 0 THEN 'No Discount'
        WHEN Discount_Percent BETWEEN 1 AND 10 THEN 'Low Discount'
        WHEN Discount_Percent BETWEEN 11 AND 20 THEN 'Medium Discount'
        ELSE 'High Discount'
    END AS Discount_Bucket,
    COUNT(*) AS Product_Count
FROM products
GROUP BY
    CASE
        WHEN Discount_Percent = 0 THEN 'No Discount'
        WHEN Discount_Percent BETWEEN 1 AND 10 THEN 'Low Discount'
        WHEN Discount_Percent BETWEEN 11 AND 20 THEN 'Medium Discount'
        ELSE 'High Discount'
    END
ORDER BY Product_Count DESC;


/* ============================================================
   SECTION 6: CUSTOMER & PAYMENT INSIGHTS
   ============================================================ */


/* Q44. What is the revenue generated by each customer tier? */

SELECT
    c.Customer_Tier,
    ROUND(SUM(s.Total_Amount), 2) AS Total_Revenue,
    COUNT(DISTINCT c.Customer_ID) AS Unique_Customers
FROM sales s
INNER JOIN customers c
    ON s.Customer_ID = c.Customer_ID
GROUP BY c.Customer_Tier
ORDER BY Total_Revenue DESC;


/* Q45. Which customers generated the highest revenue? */

SELECT
    c.Customer_ID,
    c.Customer_Name,
    ROUND(SUM(s.Total_Amount), 2) AS Customer_Revenue
FROM customers c
INNER JOIN sales s
    ON c.Customer_ID = s.Customer_ID
GROUP BY
    c.Customer_ID,
    c.Customer_Name
ORDER BY Customer_Revenue DESC
LIMIT 10;


/* Q46. What is the average order value for each payment mode? */

