/* ============================================================
   SECTION 7: DELIVERY & BUSINESS PERFORMANCE
   ============================================================ */


/* Q48. What percentage of orders were successfully delivered? */

SELECT
    ROUND(
        100.0 *
        SUM(
            CASE
                WHEN Order_Status = 'Delivered' THEN 1
                ELSE 0
            END
        ) / COUNT(*),
        2
    ) AS Delivery_Success_Percentage
FROM sales;


/* Q49. What is the average delivery time in days? */

SELECT
    ROUND(
        AVG(DATEDIFF(Delivery_Date, Order_Date)),
        2
    ) AS Average_Delivery_Days
FROM sales
WHERE Delivery_Date IS NOT NULL
  AND Order_Date IS NOT NULL;


/* Q50. Which states have the highest average delivery time? */

SELECT
    State,
    ROUND(
        AVG(DATEDIFF(Delivery_Date, Order_Date)),
        2
    ) AS Average_Delivery_Days
FROM sales
WHERE Delivery_Date IS NOT NULL
  AND Order_Date IS NOT NULL
GROUP BY State
ORDER BY Average_Delivery_Days DESC;

