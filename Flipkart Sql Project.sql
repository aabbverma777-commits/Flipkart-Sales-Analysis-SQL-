   ============================================================ */


/* Q1. How many customers are present in the database? */

SELECT COUNT(*) AS Total_Customers
FROM customers;


/* Q2. How many products are available? */

SELECT COUNT(*) AS Total_Products
FROM products;


/* Q3. How many sales/order records are present? */

SELECT COUNT(*) AS Total_Sales_Records
FROM sales;


/* Q4. What is the total revenue generated? */

SELECT ROUND(SUM(Total_Amount), 2) AS Total_Revenue
FROM sales;


/* Q5. What is the total quantity of products sold? */

SELECT SUM(Quantity) AS Total_Quantity_Sold
FROM sales;


/* Q6. What is the average order value? */

SELECT ROUND(AVG(Total_Amount), 2) AS Average_Order_Value
FROM sales;


/* Q7. What is the highest order value? */

SELECT MAX(Total_Amount) AS Highest_Order_Value
FROM sales;


/* Q8. What is the lowest order value? */

SELECT MIN(Total_Amount) AS Lowest_Order_Value
FROM sales;


/* Q9. How many unique cities are represented in the sales data? */

SELECT COUNT(DISTINCT City) AS Unique_Cities
FROM sales;


/* Q10. How many unique states are represented in the sales data? */

SELECT COUNT(DISTINCT State) AS Unique_States
FROM sales;


/* ============================================================
   SECTION : SALES & ORDER ANALYSIS
   ============================================================ */


/* Q11. How many orders are there for each order status? */

SELECT
    Order_Status,
    COUNT(*) AS Total_Orders
FROM sales
GROUP BY Order_Status
ORDER BY Total_Orders DESC;


/* Q12. Which payment methods are used by customers? */

SELECT DISTINCT Payment_Mode
FROM sales
ORDER BY Payment_Mode;


/* Q13. Which are the highest-value orders above 50,000? */

SELECT
    Order_ID,
    Customer_ID,
    Total_Amount
FROM sales
WHERE Total_Amount > 50000
ORDER BY Total_Amount DESC;


/* Q14. What is the total revenue generated by each state? */

SELECT
    State,
    ROUND(SUM(Total_Amount), 2) AS Total_Revenue
FROM sales
GROUP BY State
ORDER BY Total_Revenue DESC;


/* Q15. What are the top 10 states by revenue? */

SELECT
    State,
    ROUND(SUM(Total_Amount), 2) AS Total_Revenue
FROM sales
GROUP BY State
ORDER BY Total_Revenue DESC
LIMIT 10;


/* Q16. What is the total revenue generated by each payment mode? */

SELECT
    Payment_Mode,
    ROUND(SUM(Total_Amount), 2) AS Total_Revenue
FROM sales
GROUP BY Payment_Mode
ORDER BY Total_Revenue DESC;


/* Q17. How many orders are placed through each payment mode? */

SELECT
    Payment_Mode,
    COUNT(*) AS Total_Orders
FROM sales
GROUP BY Payment_Mode
ORDER BY Total_Orders DESC;


/* Q18. What is the total revenue generated by each order status? */

SELECT
    Order_Status,
    ROUND(SUM(Total_Amount), 2) AS Total_Revenue
FROM sales
GROUP BY Order_Status
ORDER BY Total_Revenue DESC;


/* Q19. What is the monthly revenue trend? */

SELECT
    YEAR(Order_Date) AS Order_Year,
    MONTH(Order_Date) AS Order_Month,
    MONTHNAME(Order_Date) AS Month_Name,
    ROUND(SUM(Total_Amount), 2) AS Monthly_Revenue
FROM sales
GROUP BY
    YEAR(Order_Date),
    MONTH(Order_Date),
    MONTHNAME(Order_Date)
ORDER BY
    Order_Year,
    Order_Month;


/* Q20. What is the yearly revenue? */

SELECT
    YEAR(Order_Date) AS Order_Year,
    ROUND(SUM(Total_Amount), 2) AS Yearly_Revenue
FROM sales
GROUP BY YEAR(Order_Date)
ORDER BY Order_Year;


/* ============================================================
   SECTION 3: LOCATION & CUSTOMER ANALYSIS
   ============================================================ */


/* Q21. What is the quarterly revenue? */

SELECT
    YEAR(Order_Date) AS Order_Year,
    QUARTER(Order_Date) AS Quarter_Number,
    ROUND(SUM(Total_Amount), 2) AS Quarterly_Revenue
FROM sales
GROUP BY
    YEAR(Order_Date),
    QUARTER(Order_Date)
ORDER BY
    Order_Year,
    Quarter_Number;


/* Q22. What is the revenue generated by each city? */

SELECT
    City,
    ROUND(SUM(Total_Amount), 2) AS Total_Revenue
FROM sales
GROUP BY City
ORDER BY Total_Revenue DESC;


/* Q23. What are the top 10 cities by revenue? */

SELECT
    City,
    ROUND(SUM(Total_Amount), 2) AS Total_Revenue
FROM sales
GROUP BY City
ORDER BY Total_Revenue DESC
LIMIT 10;


/* Q24. What is the total revenue generated by each
        customer age group? */

SELECT
    Customer_Age_Group,
    ROUND(SUM(Total_Amount), 2) AS Total_Revenue,
    COUNT(*) AS Total_Orders
FROM sales
GROUP BY Customer_Age_Group
ORDER BY Total_Revenue DESC;


/* Q25. Which age group has the highest number of orders? */

SELECT
    Customer_Age_Group,
    COUNT(*) AS Total_Orders
FROM sales
GROUP BY Customer_Age_Group
ORDER BY Total_Orders DESC
LIMIT 1;


/* Q26. Which age group generates the highest revenue? */

SELECT
    Customer_Age_Group,
    ROUND(SUM(Total_Amount), 2) AS Total_Revenue
FROM sales
GROUP BY Customer_Age_Group
ORDER BY Total_Revenue DESC
LIMIT 1;


/* Q27. Which states have more than 100 unique customers? */

SELECT
    State,
    COUNT(DISTINCT Customer_ID) AS Unique_Customers
FROM sales
GROUP BY State
HAVING COUNT(DISTINCT Customer_ID) > 100
ORDER BY Unique_Customers DESC;


/* Q28. Which customers have placed more than 5 orders? */

SELECT
    Customer_ID,
    COUNT(*) AS Total_Orders
FROM sales
GROUP BY Customer_ID
HAVING COUNT(*) > 5
ORDER BY Total_Orders DESC;


/* Q29. Which customers are repeat customers? */

SELECT
    Customer_ID,
    COUNT(DISTINCT Order_ID) AS Total_Orders
FROM sales
GROUP BY Customer_ID
HAVING COUNT(DISTINCT Order_ID) > 1
ORDER BY Total_Orders DESC;


