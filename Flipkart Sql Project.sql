/* Q32. Which brands have the largest number of products? */

SELECT
    Brand,
    COUNT(*) AS Product_Count
FROM products
GROUP BY Brand
ORDER BY Product_Count DESC;


/* Q33. What is the average selling price for each category? */

SELECT
    Category,
    ROUND(AVG(Selling_Price), 2) AS Average_Selling_Price
